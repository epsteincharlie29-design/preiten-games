const EXTRA_LEVELS = {};   // Text-Id -> Level-Objekt ('arena', 'raid', eigene Modi)
const FLOOR_MODS = {};     // Id -> { setup(F,L), update(dt), clientUpdate(dt), draw(g), drawScreen(g), hud(), canClear(), exit(), onKill(e,how), onPlayerDeath(p) }
const RUN_MODES = {};      // run.mode -> { update(dt), hud(), onExit(), onAllDead(), onClear() }
function levelById(li) { return typeof li === 'string' ? EXTRA_LEVELS[li] : LEVELS[li]; }
function levelLabel(li) { const L = levelById(li); return (L && L.label) || 'LEVEL ' + (typeof li === 'number' ? li + 1 : li); }
// fremde Rückrufe absichern: ein Fehler wird einmal gemeldet und bremst die Spielschleife nicht
const EXT_FAILED = new Set();
function extCall(fn, ...a) {
  try { return fn(...a); } catch (e) { if (!EXT_FAILED.has(fn)) { EXT_FAILED.add(fn); console.error(e); } return undefined; }
}
const FM_NONE = [];
// alle aktiven Etagen-Mods aufrufen (G.mods = Ids), Ergebnisse als Liste
function floorModsCall(fnName, ...args) {
  if (!G || !G.mods || !G.mods.length) return FM_NONE;
  const out = [];
  for (const id of G.mods) { const m = FLOOR_MODS[id]; if (m && typeof m[fnName] === 'function') out.push(extCall(m[fnName], ...args)); }
  return out;
}
